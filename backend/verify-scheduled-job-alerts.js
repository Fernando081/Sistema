require('reflect-metadata');
const assert = require('node:assert/strict');
const { randomBytes,randomUUID } = require('node:crypto');
const fs = require('node:fs'),path = require('node:path');
const { Client } = require('pg'),{ DataSource } = require('typeorm');
const { Test } = require('@nestjs/testing'),{ ValidationPipe } = require('@nestjs/common'),{ Reflector } = require('@nestjs/core');
const { databaseConfig } = require('./db-config');
const { syncScheduledJobAlerts } = require('./dist/common/scheduled-job-alerts');
const { runScheduledJob } = require('./dist/common/scheduled-job');
const { NotificationService } = require('./dist/notification/notification.service');
const { NotificationController } = require('./dist/notification/notification.controller');
const { AuthUser } = require('./dist/auth/auth-user.entity'),{ AuthService } = require('./dist/auth/auth.service');
const { AuthController } = require('./dist/auth/auth.controller'),{ JwtAuthGuard } = require('./dist/auth/jwt-auth.guard');
const { RolesGuard } = require('./dist/auth/roles.guard'),{ PermissionsGuard } = require('./dist/auth/permissions.guard');

async function main() {
  assert.equal(process.versions.node.split('.')[0],'24'); assert.equal(process.argv.length,2);
  const config = databaseConfig();
  assert.ok(['localhost','127.0.0.1','::1','[::1]'].includes(config.connectionString?new URL(config.connectionString).hostname:config.host));
  const schema='verify_job_alerts_'+randomBytes(8).toString('hex');
  const writer=new Client({...config,connectionTimeoutMillis:5000,statement_timeout:15000});
  let created=false,cleaned=false,source,app;
  const checks=[],checked=name=>{checks.push({name,passed:true});console.log('OK:',name);};
  const saved=Object.fromEntries(['NODE_ENV','JWT_SECRET','ALLOW_ENV_AUTH'].map(key=>[key,process.env[key]]));
  await writer.connect();
  try {
    await writer.query(`CREATE SCHEMA "${schema}"`);created=true;await writer.query(`SET search_path TO "${schema}"`);
    await writer.query(`CREATE TABLE auth_user(id_user integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username text UNIQUE NOT NULL,password_hash text NOT NULL,role text NOT NULL,is_active boolean NOT NULL DEFAULT true,token_version integer NOT NULL DEFAULT 0)`);
    await writer.query(fs.readFileSync(path.join(__dirname,'migrations/095_sesiones_por_navegador.sql'),'utf8'));
    await writer.query(fs.readFileSync(path.join(__dirname,'migrations/096_autenticacion_dos_pasos.sql'),'utf8'));
    const notificationSql=fs.readFileSync(path.join(__dirname,'migrations/064_centro_notificaciones.sql'),'utf8');
    await writer.query(notificationSql.slice(0,notificationSql.indexOf('DROP TRIGGER')));
    for(const file of ['086_estado_refresco_dashboard.sql','087_estado_jobs_operativos.sql'])
      await writer.query(fs.readFileSync(path.join(__dirname,'migrations',file),'utf8'));
    const password=randomBytes(24).toString('hex'),hash=await AuthService.hashPassword(password);
    await writer.query(`INSERT INTO auth_user(username,password_hash,role,is_active) VALUES
      ('jobs-admin',$1,'admin',true),('jobs-admin2',$1,'admin',true),('jobs-user',$1,'user',true),('jobs-inactive',$1,'admin',false)`,[hash]);
    source=new DataSource({type:'postgres',...(config.connectionString?{url:config.connectionString}:{host:config.host,port:config.port,
      username:config.user,password:config.password,database:config.database}),ssl:config.ssl,entities:[AuthUser],synchronize:false,
      extra:{options:`-c search_path=${schema}`,max:6,connectionTimeoutMillis:5000,statement_timeout:15000}});
    await source.initialize();
    const notices=()=>source.query("SELECT id_notification,id_user,type,severity,title,message,route,read_at,created_at FROM app_notification WHERE source_type='scheduled_job' ORDER BY id_user,dedupe_key");
    const sync=()=>syncScheduledJobAlerts(source);
    const fail=()=>assert.rejects(()=>runScheduledJob(source,'operational_alerts',async()=>{throw new Error('private-job-detail');},()=>{}),/private-job-detail/);
    await sync();assert.deepEqual(await notices(),[]);
    const at=async time=>(await source.query('SELECT fn_scheduled_job_status($1) jobs',[time]))[0].jobs;
    await source.query("UPDATE operational_job SET installed_at='2026-10-12T09:12:00Z' WHERE interval_seconds IS NOT NULL");
    assert.ok((await at('2026-10-12T09:24:59Z')).every(j=>!j.overdue));
    assert.ok((await at('2026-10-12T09:25:00Z')).every(j=>j.overdue));
    await source.query('UPDATE operational_job SET installed_at=clock_timestamp() WHERE interval_seconds IS NOT NULL');
    checked('Instalación sin falsa acusación y frontera diez minutos/cinco minutos de tolerancia conservadas');

    await fail();let rows=await notices();assert.equal(rows.length,2);
    assert.deepEqual(rows.map(r=>r.id_user),[1,2]);assert.ok(rows.every(r=>r.type==='scheduled_job_failed'&&r.severity==='critical'&&r.read_at===null));
    assert.ok(!JSON.stringify(rows).includes('private-job-detail'));assert.ok(rows.every(r=>r.route==='/dashboard?procesos=1'));
    checked('Fallo confirmado del runner genera aviso crítico inmediato sólo a ADMIN activos, sin detalle privado');
    await source.query("UPDATE app_notification SET read_at=clock_timestamp() WHERE id_user=1 AND source_type='scheduled_job'");
    const acknowledged=await notices();await Promise.all([sync(),sync(),sync()]);assert.deepEqual(await notices(),acknowledged);
    await fail();assert.deepEqual(await notices(),acknowledged);
    checked('Revisión concurrente/fallo reiterado conserva ID/fecha/lectura: un incidente por job y administrador, sin spam');

    for(let i=0;i<25;i++)await source.query("INSERT INTO operational_job_run(id,job_name,status,started_at) VALUES($1,'operational_alerts','running',clock_timestamp()+interval '1 minute')",[randomUUID()]);
    await sync();assert.deepEqual(await notices(),acknowledged);
    checked('Veinticinco intentos sin cierre no ocultan el último fallo finalizado ni inventan recuperación por running');
    const guard=source.createQueryRunner();await guard.connect();await guard.startTransaction();
    try {await guard.query('SELECT pg_advisory_xact_lock(72410,4)');await sync();assert.deepEqual(await notices(),acknowledged);}
    finally {await guard.rollbackTransaction();await guard.release();}
    checked('Guardia PostgreSQL real omite una revisión competidora sin cambios ni bloqueo prolongado');

    await runScheduledJob(source,'operational_alerts',async()=>{},()=>{});
    rows=await notices();assert.ok(rows.every(r=>r.type==='scheduled_job_recovered'&&r.severity==='info'&&r.read_at));
    assert.deepEqual(rows.map(r=>r.id_notification),acknowledged.map(r=>r.id_notification));
    await fail();rows=await notices();assert.ok(rows.every(r=>r.type==='scheduled_job_failed'&&r.read_at===null));
    assert.deepEqual(rows.map(r=>r.id_notification),acknowledged.map(r=>r.id_notification));
    checked('Éxito posterior resuelve; nuevo fallo reabre el mismo aviso sin duplicarlo');

    await source.query("UPDATE operational_job SET installed_at=clock_timestamp()-interval '2 hours',grace_seconds=0 WHERE name='dashboard_freshness'");
    await sync();rows=await notices();const late=rows.filter(r=>r.type==='scheduled_job_overdue');
    assert.equal(late.length,2);assert.ok(late.every(r=>r.severity==='warning'));
    const lateFingerprint=await notices();await sync();assert.deepEqual(await notices(),lateFingerprint);
    checked('Sin éxito esperado genera atraso warning independiente del fallo; repetir conserva aviso y fecha');
    await source.query(`INSERT INTO operational_job_run(id,job_name,status,started_at,finished_at)
      VALUES($1,'dashboard_freshness','success',$2::timestamptz-interval '2 microseconds',$2::timestamptz-interval '1 microsecond')`,[randomUUID(),late[0].created_at]);
    await source.query("UPDATE operational_job SET grace_seconds=86400 WHERE name='dashboard_freshness'");
    assert.equal((await source.query('SELECT fn_scheduled_job_status() jobs'))[0].jobs.find(job=>job.name==='dashboard_freshness').overdue,false);
    await sync();assert.deepEqual(await notices(),lateFingerprint);
    await source.query("INSERT INTO operational_job_run(id,job_name,status) VALUES($1,'dashboard_freshness','running')",[randomUUID()]);
    await sync();assert.deepEqual(await notices(),lateFingerprint);
    checked('Éxito anterior al incidente o intento pendiente no pueden cerrar una alerta aunque el estado de frescura cambie');
    await runScheduledJob(source,'dashboard_freshness',async()=>{},()=>{});
    await source.query("UPDATE operational_job SET grace_seconds=300 WHERE name='dashboard_freshness'");
    assert.ok((await notices()).filter(r=>r.id_notification===late[0].id_notification||r.id_notification===late[1].id_notification).every(r=>r.type==='scheduled_job_recovered'));
    checked('Atraso sólo se resuelve con un éxito posterior comprobado y proceso al día');

    Object.assign(process.env,{NODE_ENV:'test',JWT_SECRET:randomBytes(32).toString('hex'),ALLOW_ENV_AUTH:'false'});
    const auth=new AuthService(source.getRepository(AuthUser)),notifications=new NotificationService(source);
    const module=await Test.createTestingModule({controllers:[AuthController,NotificationController],providers:[
      {provide:AuthService,useValue:auth},{provide:NotificationService,useValue:notifications}]}).compile();
    app=module.createNestApplication({logger:false});app.setGlobalPrefix('api/v1');const reflector=new Reflector();
    app.useGlobalGuards(new JwtAuthGuard(reflector,auth),new RolesGuard(reflector),new PermissionsGuard(reflector,source));
    app.useGlobalPipes(new ValidationPipe({whitelist:true,forbidNonWhitelisted:true,transform:true}));
    await app.listen(0,'127.0.0.1');const url=(await app.getUrl())+'/api/v1';
    const login=async username=>{const response=await fetch(url+'/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},
      body:JSON.stringify({username,password}),signal:AbortSignal.timeout(10000)});assert.equal(response.status,201);return(await response.json()).access_token;};
    const jobRunCount=(await source.query('SELECT count(*)::int n FROM operational_job_run'))[0].n;
    const token=await login('jobs-admin'),other=await login('jobs-admin2'),user=await login('jobs-user');
    const list=async jwt=>{const response=await fetch(url+'/notifications',{headers:jwt?{Authorization:'Bearer '+jwt}:{},signal:AbortSignal.timeout(10000)});
      return{status:response.status,cache:response.headers.get('cache-control'),body:await response.json()};};
    assert.equal((await list()).status,401);const adminList=await list(token);assert.equal(adminList.status,200);assert.equal(adminList.body.items.length,2);
    assert.equal(adminList.cache,'private, no-store');
    assert.equal((await list(user)).body.items.length,0);assert.equal((await list(user)).body.unread,0);
    assert.equal((await list(other)).body.items.length,2);
    const foreign=(await notices()).find(r=>r.id_user===2&&r.type==='scheduled_job_failed');
    await fetch(url+'/notifications/'+foreign.id_notification+'/read',{method:'POST',headers:{Authorization:'Bearer '+token},signal:AbortSignal.timeout(10000)});
    assert.equal((await notices()).find(r=>r.id_notification===foreign.id_notification).read_at,null);
    assert.equal((await source.query('SELECT count(*)::int n FROM operational_job_run'))[0].n,jobRunCount);
    checked('Login bcrypt/JWT/SQL y notificaciones reales: anónimo401, ADMIN200, operador sin avisos, lectura ajena protegida y sin cron ficticio');
    await source.query("UPDATE auth_user SET role='user',token_version=token_version+1 WHERE id_user=2");
    const demoted=await login('jobs-admin2');const hidden=await list(demoted);assert.equal(hidden.body.items.length,0);assert.equal(hidden.body.unread,0);
    assert.equal((await list(other)).status,401);
    checked('Al perder rol ADMIN desaparecen avisos e unread de jobs; JWT previo revocado y avisos históricos conservados');
    assert.equal((await source.query("SELECT count(*)::int n FROM app_notification WHERE id_user=4 AND source_type='scheduled_job'"))[0].n,0);
    assert.equal((await source.query("SELECT count(*)::int n FROM pg_stat_activity WHERE datname=current_database() AND state LIKE 'idle in transaction%'"))[0].n,0);
    checked('Sin alertas para administrador inactivo, secretos en avisos o transacciones ociosas finales');
  } finally {
    if(app)await app.close();if(source?.isInitialized)await source.destroy();
    for(const [key,value]of Object.entries(saved)){if(value===undefined)delete process.env[key];else process.env[key]=value;}
    if(created&&/^verify_job_alerts_[a-f0-9]{16}$/.test(schema)){
      await writer.query(`DROP SCHEMA "${schema}" CASCADE`);cleaned=!(await writer.query('SELECT 1 FROM pg_namespace WHERE nspname=$1',[schema])).rowCount;}
    await writer.end();
  }
  assert.ok(cleaned);checked('Sólo el esquema propio eliminado y servidor/conexiones cerrados');
  fs.writeFileSync(path.join(__dirname,'../.artifacts/o024-job-alerts-db.json'),JSON.stringify({phase:'O02.4',generatedAt:new Date().toISOString(),
    node:process.versions.node,source:'isolated-test-schema',checks,cleaned,limits:['No AppModule completo o monitor externo; incidentes sólo en esquema propio.']},null,2)+'\n');
  console.log(`Avisos de jobs: ${checks.length}/${checks.length} grupos aprobados.`);
}
main().catch(error=>{console.error('Falló verificación de avisos:',error instanceof assert.AssertionError?error.message:error.code||error.name);process.exitCode=1;});
