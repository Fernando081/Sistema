require('reflect-metadata');
const assert = require('node:assert/strict');
const { randomBytes, randomUUID, createHash } = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { Client } = require('pg');
const { DataSource } = require('typeorm');
const { Test } = require('@nestjs/testing');
const { ValidationPipe } = require('@nestjs/common');
const { Reflector } = require('@nestjs/core');
const { databaseConfig } = require('./db-config');
const { CrmWebMetricsService } = require('./dist/crm/crm-web-metrics.service');
const { CrmSolicitudesWebService } = require('./dist/crm/crm-solicitudes-web.service');
const { CrmSolicitudesWebController } = require('./dist/crm/crm-solicitudes-web.controller');
const { CrmSolicitudesWebMaintenance } = require('./dist/crm/crm-solicitudes-web-maintenance.service');
const { AuthUser } = require('./dist/auth/auth-user.entity');
const { AuthService } = require('./dist/auth/auth.service');
const { AuthController } = require('./dist/auth/auth.controller');
const { JwtAuthGuard } = require('./dist/auth/jwt-auth.guard');
const { RolesGuard } = require('./dist/auth/roles.guard');
const { PermissionsGuard } = require('./dist/auth/permissions.guard');

async function main() {
  assert.equal(process.versions.node.split('.')[0], '24', 'Usa Node.js 24');
  assert.equal(process.argv.length, 2, 'Este verificador no admite argumentos');
  const config = databaseConfig();
  const host = config.connectionString ? new URL(config.connectionString).hostname : config.host;
  assert.ok(['127.0.0.1', 'localhost', '::1', '[::1]'].includes(host), 'La verificación exige PostgreSQL local');
  const schema = 'verify_web_metrics_' + randomBytes(8).toString('hex');
  const admin = new Client({ ...config, connectionTimeoutMillis: 5000, statement_timeout: 15000 });
  const saved = Object.fromEntries(['NODE_ENV', 'JWT_SECRET', 'ALLOW_ENV_AUTH'].map(key => [key, process.env[key]]));
  const checks = [];
  const checked = name => { checks.push({ name, passed: true }); console.log('OK:', name); };
  let created = false, db, app, readonlyChecks = 0, report, sourceUnchanged = false, cleaned = false;
  await admin.connect();
  try {
    await admin.query(`CREATE SCHEMA "${schema}"`); created = true;
    await admin.query(`SET search_path TO "${schema}"`);
    await admin.query(`CREATE TABLE auth_user(id_user integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username varchar(100) UNIQUE NOT NULL,password_hash text NOT NULL,role varchar(20) NOT NULL,
      is_active boolean NOT NULL DEFAULT true,token_version integer NOT NULL DEFAULT 0)`);
    await admin.query(fs.readFileSync(path.join(__dirname,'migrations/095_sesiones_por_navegador.sql'),'utf8'));
    await admin.query(fs.readFileSync(path.join(__dirname,'migrations/096_autenticacion_dos_pasos.sql'),'utf8'));
    const password = randomBytes(24).toString('hex');
    const hash = await AuthService.hashPassword(password);
    await admin.query(`INSERT INTO auth_user(username,password_hash,role) VALUES ('metrics-admin',$1,'admin'),('metrics-user',$1,'user')`, [hash]);
    await admin.query('CREATE TABLE cliente("IdCliente" integer PRIMARY KEY)');
    await admin.query(fs.readFileSync(path.join(__dirname, 'migrations/031_crm_pipeline.sql'), 'utf8').split('CREATE TABLE IF NOT EXISTS venta_perdida')[0]);
    for (const file of ['089_solicitudes_web.sql', '090_conversion_solicitud_web.sql'])
      await admin.query(fs.readFileSync(path.join(__dirname, 'migrations', file), 'utf8'));
    await require('./test-support/web-commercial-schema').setupCommercialSchema(admin);
    db = new DataSource({ type: 'postgres', ...(config.connectionString ? { url: config.connectionString } :
      { host: config.host, port: config.port, username: config.user, password: config.password, database: config.database }),
      ssl: config.ssl, entities: [AuthUser], synchronize: false,
      extra: { options: `-c search_path=${schema}`, connectionTimeoutMillis: 5000 }, logging: false });
    await db.initialize();
    const inbox = new CrmSolicitudesWebService(db);
    // The adapter delegates to a real TypeORM transaction; no result is mocked.
    const metrics = new CrmWebMetricsService({ transaction: (isolation, work) => db.transaction(isolation, manager => work({
      query: async (sql, parameters) => {
        if (sql.startsWith('WITH bounds')) {
          const [settings] = await manager.query(`SELECT current_setting('transaction_read_only') AS readonly,
            current_setting('transaction_isolation') AS isolation,current_setting('statement_timeout') AS timeout`);
          assert.deepEqual(settings, { readonly: 'on', isolation: 'repeatable read', timeout: '5s' }); readonlyChecks++;
        }
        return manager.query(sql, parameters);
      },
    })) });
    const piece = (code, brand, quantity, application = '') => ({ kind: 'reference', code, brand, quantity, application });
    const makeLead = items => ({ schemaVersion: 1, requestId: randomUUID(), origin: 'public-web',
      contact: { name: 'CONTACT-DO-NOT-EXPOSE', channel: 'email', value: 'private@example.invalid' }, items,
      privacy: { accepted: true, version: 'fixture-only' } });
    const put = async (createdAt, items, state = 'Pendiente', conversion) => {
      const lead = makeLead(items); await inbox.receive(lead, 'a'.repeat(64));
      await db.query('UPDATE crm_solicitud_web SET created_at=$2 WHERE request_id=$1', [lead.requestId, createdAt]);
      if (conversion) {
        const linked = await inbox.convert(lead.requestId, 1, 1);
        await db.query('UPDATE crm_oportunidad SET etapa=$2 WHERE id_oportunidad=$1', [linked.idOportunidad, conversion]);
      } else if (state !== 'Pendiente') await inbox.review(lead.requestId, state, 1, 1);
      return lead;
    };
    await put('2026-10-01T05:59:59.999Z', [piece('EXCLUDED-BEFORE', '', 9)]);
    const first = await put('2026-10-01T06:00:00Z', [piece('OEM-A', 'Timken', 2), piece('OEM-A', 'Other', 3)]);
    const reviewed = await put('2026-10-02T05:59:59.999Z', [piece('OEM-A', 'Timken', 1)], 'Revisada');
    const won = await put('2026-10-02T06:00:00Z', [piece('OEM-A', 'Timken', 5), piece('OEM-A', 'Timken', 3, 'Another')], 'Pendiente', 'Ganada');
    const lost = await put('2026-10-03T06:00:00Z', [piece('OEM-B', 'SKF', 4)], 'Pendiente', 'Perdida');
    const expired = await put('2026-10-03T12:00:00Z', [piece('EXPIRED-DO-NOT-EXPOSE', '', 4)]);
    await put('2026-10-03T15:00:00Z', [piece('OEM-B', 'SKF', 1)], 'Descartada');
    await put('2026-10-04T06:00:00Z', [piece('EXCLUDED-AFTER', '', 9)]);
    await db.query(`UPDATE crm_solicitud_web SET expires_at=clock_timestamp()-interval '1 hour' WHERE request_id=ANY($1::uuid[])`,
      [[won.requestId, lost.requestId, expired.requestId]]);
    await db.query('UPDATE crm_solicitud_web SET payload=NULL WHERE request_id=$1', [lost.requestId]);
    await inbox.receive(first, 'a'.repeat(64)); await inbox.receive(lost, 'a'.repeat(64));
    const fingerprint = async () => {
      const rows = await db.query(`SELECT (SELECT jsonb_agg(w ORDER BY request_id) FROM crm_solicitud_web w) AS inbox,
        (SELECT jsonb_agg(o ORDER BY id_oportunidad) FROM crm_oportunidad o) AS opportunities,
        (SELECT jsonb_agg(s ORDER BY id_oportunidad) FROM crm_oportunidad_consulta_web s) AS snapshots`);
      return createHash('sha256').update(JSON.stringify(rows)).digest('hex');
    };
    const before = await fingerprint();
    report = await metrics.report('2026-10-01', '2026-10-03');
    assert.deepEqual(report.totals, { recibidas: 6, pendientes: 2, revisadasSinOportunidad: 1, descartadas: 1,
      oportunidades: 2, abiertasCrm: 0, ganadasCrm: 1, perdidasCrm: 1, vigentes: 3, vencidas: 2, purgadas: 1,
      piezasVigentes: 3, piezasSnapshot: 2, sinPiezas: 1 });
    assert.equal(report.conversionPct, 33.33);
    assert.deepEqual(report.daily, [
      { fecha: '2026-10-01', recibidas: 2, oportunidades: 0 },
      { fecha: '2026-10-02', recibidas: 1, oportunidades: 1 },
      { fecha: '2026-10-03', recibidas: 3, oportunidades: 1 },
    ]);
    assert.deepEqual(report.references, [
      { code: 'OEM-A', brand: 'Timken', solicitudes: 3, cantidad: 11 },
      { code: 'OEM-B', brand: 'SKF', solicitudes: 2, cantidad: 5 },
      { code: 'OEM-A', brand: 'Other', solicitudes: 1, cantidad: 3 },
    ]);
    const encoded = JSON.stringify(report);
    for (const privateValue of ['CONTACT-DO-NOT-EXPOSE', 'private@example.invalid', 'fingerprint', 'requestId',
      'EXPIRED-DO-NOT-EXPOSE', 'EXCLUDED-BEFORE', 'EXCLUDED-AFTER']) assert.ok(!encoded.includes(privateValue));
    checked('Cohorte inclusiva en zona local, estados, 33.33%, diarios, marcas distintas y solicitudes únicas');
    checked('Piezas vigentes/snapshot tras vencimiento y purga; contactos e identificadores privados omitidos');
    const empty = await metrics.report('2025-02-01', '2025-02-03');
    assert.equal(empty.totals.recibidas, 0); assert.equal(empty.conversionPct, null); assert.deepEqual(empty.references, []);
    assert.equal(empty.daily.length, 3); assert.ok(empty.daily.every(day => !day.recibidas && !day.oportunidades));
    checked('Periodo vacío conserva días cero y conversión indefinida');
    for (const [from, until] of [['2025-02-29', '2025-03-01'], ['2026-10-04', '2026-10-03'],
      ['2025-01-01', '2026-01-02'], ["2026-10-01' OR TRUE", '2026-10-03']]) await assert.rejects(metrics.report(from, until));
    checked('Fechas imposibles, orden, exceso de periodo e inyección rechazados');
    Object.assign(process.env, { NODE_ENV: 'test', JWT_SECRET: randomBytes(32).toString('hex'), ALLOW_ENV_AUTH: 'false' });
    const auth = new AuthService(db.getRepository(AuthUser));
    const module = await Test.createTestingModule({ controllers: [AuthController, CrmSolicitudesWebController], providers: [
      { provide: AuthService, useValue: auth }, { provide: CrmSolicitudesWebService, useValue: inbox },
      { provide: CrmWebMetricsService, useValue: metrics },
      { provide: CrmSolicitudesWebMaintenance, useValue: { status: () => ({ enabled: false }) } },
    ] }).compile();
    app = module.createNestApplication({ logger: false }); app.setGlobalPrefix('api/v1');
    app.useGlobalPipes(new ValidationPipe({ whitelist: true, forbidNonWhitelisted: true, transform: true,
      validationError: { target: false, value: false } }));
    const reflector = new Reflector();
    app.useGlobalGuards(new JwtAuthGuard(reflector, auth), new RolesGuard(reflector), new PermissionsGuard(reflector, db));
    await app.listen(0, '127.0.0.1');
    const url = (await app.getUrl()) + '/api/v1';
    const login = async username => {
      const res = await fetch(url + '/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ username, password }), signal: AbortSignal.timeout(15000) });
      assert.equal(res.status, 201); return (await res.json()).access_token;
    };
    const tokens = { admin: await login('metrics-admin'), user: await login('metrics-user') };
    const get = (query, token) => fetch(url + '/crm/solicitudes-web/metricas?' + query,
      { headers: token ? { Authorization: 'Bearer ' + token } : {}, signal: AbortSignal.timeout(15000) });
    const valid = 'desde=2026-10-01&hasta=2026-10-03';
    assert.equal((await get(valid)).status, 401); assert.equal((await get(valid, tokens.user)).status, 403);
    assert.equal((await get(valid, tokens.admin.slice(0, -5) + 'AAAAA')).status, 401);
    for (const query of ['desde=2026-10-01', 'desde=bad&hasta=2026-10-03', valid + '&contact=private',
      'desde=2025-02-29&hasta=2025-03-01', 'desde=2026-10-04&hasta=2026-10-03',
      'desde=2025-01-01&hasta=2026-01-02', valid + '&desde=2026-10-02']) assert.equal((await get(query, tokens.admin)).status, 400);
    const response = await get(valid, tokens.admin);
    assert.equal(response.status, 200); assert.equal(response.headers.get('cache-control'), 'private, no-store');
    const httpReport = await response.json(); assert.deepEqual(httpReport.totals, report.totals);
    await db.query('UPDATE auth_user SET token_version=token_version+1 WHERE username=$1', ['metrics-admin']);
    assert.equal((await get(valid, tokens.admin)).status, 401);
    checked('Login PostgreSQL/bcrypt/JWT y guards reales: anónimo401, USER403, firma/revocación401, DTO400 y ADMIN200 no-store');
    sourceUnchanged = (await fingerprint()) === before; assert.ok(sourceUnchanged);
    assert.ok(readonlyChecks >= 3);
    checked('Lecturas REPEATABLE READ READ ONLY y plazo SQL5s comprobados; solicitudes/oportunidades/snapshots sin cambios');
    // Legacy malformed data must not cause a cast or array-expansion SQL error.
    await db.query(`UPDATE crm_solicitud_web SET payload=jsonb_set(payload,'{items}',$2::jsonb) WHERE request_id=$1`,
      [reviewed.requestId, JSON.stringify([{ code: 'BAD-QTY', brand: '', quantity: 10000 }])]);
    const malformed = await metrics.report('2026-10-01', '2026-10-03');
    assert.ok(!malformed.references.some(item => item.code === 'BAD-QTY'));
    await db.query(`UPDATE crm_solicitud_web SET payload=jsonb_set(payload,'{items}','"not-array"'::jsonb) WHERE request_id=$1`, [reviewed.requestId]);
    assert.equal((await metrics.report('2026-10-01', '2026-10-03')).totals.sinPiezas, 2);
    checked('Cantidades fuera de contrato y listas antiguas malformadas se omiten sin fallar la consulta');
  } finally {
    if (app) await app.close();
    if (db?.isInitialized) await db.destroy();
    for (const [key, value] of Object.entries(saved)) { if (value === undefined) delete process.env[key]; else process.env[key] = value; }
    if (created && /^verify_web_metrics_[a-f0-9]{16}$/.test(schema)) {
      await admin.query(`DROP SCHEMA "${schema}" CASCADE`);
      cleaned = !(await admin.query('SELECT 1 FROM pg_namespace WHERE nspname=$1', [schema])).rowCount;
    }
    await admin.end();
  }
  assert.ok(cleaned);
  checked('Esquema desechable propio eliminado y conexiones/servidor cerrados');
  const artifact = path.resolve(__dirname, '../.artifacts/web-metrics-db.json');
  fs.mkdirSync(path.dirname(artifact), { recursive: true });
  fs.writeFileSync(artifact, JSON.stringify({ phase: 'WEB05.2a', source: 'isolated-test-fixtures',
    generatedAt: new Date().toISOString(), node: process.versions.node, checks, readonlyChecks, sourceUnchanged,
    cleaned, report, limits: ['Esquema mínimo; no AppModule completo, cron, carga masiva o métricas comerciales reales.'] }, null, 2) + '\n');
  console.log(`Medición web aislada: ${checks.length}/${checks.length} grupos aprobados. Evidencia: .artifacts/web-metrics-db.json`);
}
main().catch(error => { console.error('Falló la verificación de medición web:', error.name,
  error instanceof assert.AssertionError ? error.message : 'Error de servicio/SQL; secretos omitidos'); process.exitCode = 1; });
