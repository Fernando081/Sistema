import { BadRequestException, ConflictException, ForbiddenException, Injectable, NotFoundException, ServiceUnavailableException } from '@nestjs/common';
import { DataSource } from 'typeorm';
import { createHash } from 'node:crypto';
import PdfPrinter from 'pdfmake';
import { Content, TDocumentDefinitions } from 'pdfmake/interfaces';
import { JwtPayload } from '../auth/auth.types';
import { setAuditActor } from '../auth/audit-actor';
import { QueryExecutor, queryRows, readSnapshot } from '../common/database/typed-query';
import { imageExtension } from '../upload/image-validation';
import { PersistenciaPedidoService } from './persistencia-pedido.service';
import { EntregaEvidenciaDto } from './entrega-evidencia.dto';
const digest=(value:Buffer|string)=>createHash('sha256').update(value).digest('hex');
const permission='pedidos.entregas';
type Kind='firma'|'foto';
type Files=Partial<Record<Kind,Express.Multer.File[]>>;
export interface Snapshot {
 folio:number;cliente:string;recibidoPor:string;notas:string;motivoSinEvidencia:string;
 ubicacion:{latitud:number;longitud:number;precision:number;fecha:string}|null;
 partidas:{codigo:string;descripcion:string;cantidad:string}[];
 archivos:{tipo:Kind;mime:string;bytes:number;sha256:string}[];
}
export interface Evidence {idEntrega:string;creadaEn:string;autor:string;snapshot:Snapshot;sha256:string;}
@Injectable()
export class EntregaEvidenciaService {
 constructor(private readonly source:DataSource,private readonly orders:PersistenciaPedidoService){}
 private async actor(manager:QueryExecutor,actor:JwtPayload,write=false){
  const [user]=await queryRows<{id:number;nombre:string}>(manager,`SELECT id_user AS id,username AS nombre FROM auth_user
   WHERE id_user=$1 AND is_active AND role=$2 AND token_version=$3 AND fn_effective_permission(id_user,role,$4) ${write?'FOR SHARE':''}`,
   [actor.idUser??null,actor.role,actor.version,permission]);
  if(!user)throw new ForbiddenException('Tu cuenta o permiso de entregas cambió. Inicia sesión nuevamente.');
  if(write)await setAuditActor(manager,user.id);return user;
 }
 private async evidence(manager:QueryExecutor,id:number){
  const [row]=await queryRows<Evidence>(manager,`SELECT e.id_entrega AS "idEntrega",e.creada_en AS "creadaEn",e.autor_nombre AS autor,e.snapshot,e.sha256
   FROM pedido_entrega_evidencia e JOIN entrega_pedido d USING(id_entrega) WHERE d.id_pedido=$1`,[id]);
  // jsonb can reorder keys; fingerprint uses the canonical text generated by PostgreSQL.
  if(row){const [check]=await queryRows<{sha:string}>(manager,'SELECT encode(sha256(convert_to(snapshot::text,\'UTF8\')),\'hex\') AS sha FROM pedido_entrega_evidencia WHERE id_entrega=$1',[row.idEntrega]);
   if(check.sha!==row.sha256)throw new ServiceUnavailableException('El comprobante no coincide con su huella; revisa el respaldo.');}
  return row??null;
 }
 async status(id:number,actor:JwtPayload){return readSnapshot(this.source,async manager=>{
  await this.actor(manager,actor);const [order]=await queryRows<{estado:string;version:number}>(manager,'SELECT estado,version FROM pedido_venta WHERE id_pedido=$1',[id]);
  if(!order)throw new NotFoundException('Pedido no encontrado');const evidence=await this.evidence(manager,id);
  const [legacy]=await queryRows(manager,'SELECT recibido_por AS "recibidoPor",notas,created_at AS fecha FROM entrega_pedido WHERE id_pedido=$1',[id]);
  return{...order,evidencia:evidence,entregaAnterior:evidence?null:legacy??null};
 });}
 register(id:number,dto:EntregaEvidenciaDto,files:Files,actor:JwtPayload){
  dto.requestId=dto.requestId.toLowerCase();
  const uploads=Object.entries(files).flatMap(([kind,list])=>(list??[]).map(file=>({kind:kind as Kind,file})));
  for(const {kind,file}of uploads){if(!['firma','foto'].includes(kind)||!file.buffer.length||file.buffer.length>5*1024*1024||
   !['image/png','image/jpeg','image/webp'].includes(file.mimetype)||!imageExtension(file.buffer,file.mimetype)||
   (kind==='firma'&&(file.mimetype!=='image/png'||file.buffer.length>512*1024)))throw new BadRequestException('Firma: PNG hasta512KiB. Foto: JPEG/PNG/WebP hasta5MiB con formato válido.');}
  if(!uploads.length&&!dto.motivoSinEvidencia?.trim())throw new BadRequestException('Adjunta firma/foto o explica por qué no se recabó evidencia.');
  const geo=[dto.latitud,dto.longitud,dto.precision,dto.ubicacionFecha],hasGeo=geo.some(v=>v!==undefined&&v!==null);
  if(hasGeo&&(geo.some(v=>v===undefined||v===null)||!dto.ubicacionFecha))
   throw new BadRequestException('La ubicación requiere coordenadas, precisión y fecha de captura de los últimos10 minutos.');
  const fields={recibidoPor:dto.recibidoPor,notas:dto.notas??'',motivoSinEvidencia:dto.motivoSinEvidencia??'',
   ubicacion:hasGeo?{latitud:dto.latitud!,longitud:dto.longitud!,precision:dto.precision!,fecha:new Date(dto.ubicacionFecha!).toISOString()}:null,
   archivos:uploads.map(({kind,file})=>({tipo:kind,mime:file.mimetype,bytes:file.buffer.length,sha256:digest(file.buffer)})).sort((a,b)=>a.tipo.localeCompare(b.tipo))};
  const hash=digest(JSON.stringify({id,version:dto.version,...fields}));
  return this.source.transaction(async manager=>{
   await manager.query("SET LOCAL statement_timeout='10s'");const user=await this.actor(manager,actor,true);
   // Global request lock also serializes accidental UUID reuse on different orders.
   await manager.query("SELECT pg_advisory_xact_lock(hashtextextended($1,0))",['entrega:'+dto.requestId]);
   const order=await this.orders.lockOrder(manager,id);
   const [previous]=await queryRows<{huella:string;idPedido:number}>(manager,`SELECT e.huella,d.id_pedido AS "idPedido" FROM pedido_entrega_evidencia e JOIN entrega_pedido d USING(id_entrega) WHERE e.request_id=$1`,[dto.requestId]);
   if(previous){if(previous.idPedido!==id||previous.huella!==hash)throw new ConflictException('La clave de entrega ya identifica otros datos');return this.evidence(manager,id);}
   if(dto.ubicacionFecha&&Math.abs(Date.now()-Date.parse(dto.ubicacionFecha))>10*60000)throw new BadRequestException('Actualiza la ubicación: la captura debe ser de los últimos10 minutos.');
   if(order.estado!=='Surtido'||order.version!==dto.version)throw new ConflictException('El pedido cambió o no está completamente surtido. Actualiza antes de entregar.');
   const [header]=await queryRows<{folio:number;cliente:string}>(manager,`SELECT p.folio,c."RazonSocial" AS cliente FROM pedido_venta p JOIN cliente c ON c."IdCliente"=p.id_cliente WHERE p.id_pedido=$1`,[id]);
   const partidas=await queryRows<Snapshot['partidas'][number]>(manager,`SELECT p."Codigo" AS codigo,d.descripcion,d.cantidad::text FROM pedido_venta_detalle d JOIN producto p ON p."IdProducto"=d.id_producto WHERE d.id_pedido=$1 ORDER BY d.id_detalle`,[id]);
   const snapshot:Snapshot={...header,...fields,partidas};
   const [delivery]=await queryRows<{id:string}>(manager,'INSERT INTO entrega_pedido(id_pedido,recibido_por,notas,id_user)VALUES($1,$2,$3,$4)RETURNING id_entrega AS id',[id,dto.recibidoPor,fields.notas,user.id]);
   await manager.query(`INSERT INTO pedido_entrega_evidencia(id_entrega,request_id,huella,autor_nombre,snapshot,sha256)
    VALUES($1,$2,$3,$4,$5::jsonb,encode(sha256(convert_to(($5::jsonb)::text,'UTF8')),'hex'))`,[delivery.id,dto.requestId,hash,user.nombre,JSON.stringify(snapshot)]);
   for(const {kind,file}of uploads)await manager.query('INSERT INTO pedido_entrega_archivo(id_entrega,tipo,mime,sha256,contenido)VALUES($1,$2,$3,$4,$5)',[delivery.id,kind,file.mimetype,digest(file.buffer),file.buffer]);
   await manager.query("UPDATE pedido_venta SET estado='Entregado',updated_at=now(),version=version+1 WHERE id_pedido=$1",[id]);
   await this.orders.history(manager,id,'Surtido','Entregado','Entrega evidenciada; receptor declarado: '+dto.recibidoPor,user.id);
   return this.evidence(manager,id);
  });
 }
 file(id:number,kind:string,actor:JwtPayload){return readSnapshot(this.source,async manager=>{
  await this.actor(manager,actor);if(!['firma','foto'].includes(kind))throw new NotFoundException('Archivo no disponible');
  const evidence=await this.evidence(manager,id);if(!evidence)throw new NotFoundException('Sin comprobante evidenciado');
  const [row]=await queryRows<{mime:string;contenido:Buffer;sha256:string}>(manager,'SELECT mime,contenido,sha256 FROM pedido_entrega_archivo WHERE id_entrega=$1 AND tipo=$2',[evidence.idEntrega,kind]);
  const meta=evidence.snapshot.archivos.find(f=>f.tipo===kind);
  if(!row||!meta)throw new NotFoundException('Archivo no disponible');
  if(digest(row.contenido)!==row.sha256||row.sha256!==meta.sha256||row.mime!==meta.mime||row.contenido.length!==meta.bytes)throw new ServiceUnavailableException('El archivo no coincide con su huella; revisa el respaldo.');
  return row;
 });}
 async pdf(id:number,actor:JwtPayload){
  const {evidencia:e}=await this.status(id,actor);if(!e)throw new NotFoundException('Sin comprobante evidenciado; la entrega anterior conserva receptor/notas.');
  const s=e.snapshot;const definition:TDocumentDefinitions={pageSize:'LETTER',pageMargins:40,defaultStyle:{font:'Helvetica',fontSize:10},content:[
   {text:'Refacciones y Tractorepuestos Tampico',bold:true,fontSize:17},
   {text:'COMPROBANTE INTERNO DE ENTREGA',margin:[0,12,0,8],fontSize:14},
   {text:`Pedido ${s.folio} · Comprobante ${e.idEntrega}`},{text:`Cliente: ${s.cliente}`},
   {text:`Fecha de registro: ${new Date(e.creadaEn).toISOString()} (UTC)`},{text:`Registró: ${e.autor}`},{text:`Recibió (declarado): ${s.recibidoPor}`,margin:[0,6,0,10]},
   {table:{headerRows:1,widths:['auto','*','auto'],body:[['Parte','Descripción','Cantidad'],...s.partidas.map(p=>[p.codigo,p.descripcion,p.cantidad])]}},
   {text:'Notas: '+(s.notas||'Sin notas'),margin:[0,10,0,8]},
   ...s.archivos.map((f):Content=>({text:`${f.tipo==='firma'?'Firma capturada':'Foto'}: ${f.mime}, ${f.bytes} bytes\nSHA-256: ${f.sha256}`,margin:[0,0,0,6],fontSize:8})),
   {text:s.motivoSinEvidencia?'Motivo declarado: '+s.motivoSinEvidencia:''},
   {text:s.ubicacion?`Ubicación reportada por dispositivo: ${s.ubicacion.latitud}, ${s.ubicacion.longitud}; precisión ±${s.ubicacion.precision}m; captura ${s.ubicacion.fecha}`:'Ubicación: no recabada',margin:[0,8,0,8]},
   {text:`Huella del snapshot: ${e.sha256}`,fontSize:8},
   {text:'Evidencias originales disponibles en el ERP con permiso. No acredita identidad ni geolocalización verificada. No es firma electrónica avanzada, factura fiscal ni comprobante de pago.',fontSize:9,margin:[0,14,0,0]},
  ]};
  const printer=new PdfPrinter({Helvetica:{normal:'Helvetica',bold:'Helvetica-Bold',italics:'Helvetica-Oblique',bolditalics:'Helvetica-BoldOblique'}});
  return new Promise<Buffer>((resolve,reject)=>{const document=printer.createPdfKitDocument(definition),chunks:Buffer[]=[];document.on('data',(b:Buffer)=>chunks.push(b));document.on('end',()=>resolve(Buffer.concat(chunks)));document.on('error',reject);document.end();});
 }
}
