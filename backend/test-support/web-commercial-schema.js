const fs = require('node:fs');
const path = require('node:path');

// Only called after the verifier has created and selected its own schema. Never
// use this helper to prepare or migrate the operational public schema.
async function setupCommercialSchema(client) {
  const selected = (await client.query('SELECT current_schema() AS name')).rows[0].name;
  if (!/^verify_web_(metrics|commercial|financial)_[a-f0-9]{16}$/.test(selected)) throw new Error('Esquema de verificación no permitido');
  await client.query('ALTER TABLE cliente ADD COLUMN IF NOT EXISTS "RazonSocial" text');
  await client.query('ALTER TABLE crm_oportunidad ADD COLUMN IF NOT EXISTS version integer NOT NULL DEFAULT 1');
  await client.query(`CREATE TABLE cotizacion(id_cotizacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente integer NOT NULL REFERENCES cliente("IdCliente"),folio integer NOT NULL,fecha_emision timestamptz NOT NULL DEFAULT now(),estatus text NOT NULL DEFAULT 'Pendiente');
    CREATE TABLE pedido_venta(id_pedido integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente integer NOT NULL REFERENCES cliente("IdCliente"),id_cotizacion integer REFERENCES cotizacion(id_cotizacion),estado text NOT NULL DEFAULT 'Facturado');
    CREATE TABLE gasto(id_gasto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,monto numeric(18,2),
      anulado boolean NOT NULL DEFAULT false,metodo_pago text,categoria text);
    CREATE TABLE factura(id_factura integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_cliente integer,
    id_cotizacion integer REFERENCES cotizacion(id_cotizacion),id_pedido integer REFERENCES pedido_venta(id_pedido),
    tipo_comprobante text NOT NULL DEFAULT 'I',estatus text DEFAULT 'Pendiente',serie text,
    moneda text,tipo_cambio numeric(18,6) DEFAULT 1,subtotal numeric(18,2),descuento numeric(18,2),total_impuestos_trasladados numeric(18,2),
    total_impuestos_retenidos numeric(18,2),total numeric(18,2),saldo_pendiente numeric(18,2),
    id_factura_global integer REFERENCES factura(id_factura),id_factura_origen integer REFERENCES factura(id_factura),
    metodo_reembolso text,id_gasto_reembolso integer REFERENCES gasto(id_gasto));
    CREATE TABLE conceptofactura(id_concepto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_factura integer REFERENCES factura(id_factura),id_producto integer,cantidad numeric(18,6),
      importe numeric(18,2),descuento numeric(18,2),importe_iva numeric(18,2),importe_ret_isr numeric(18,2),costo_unitario_snapshot numeric(18,6));
    CREATE TABLE devolucion(id_devolucion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_factura integer REFERENCES factura(id_factura),monto_total numeric(10,2),metodo_reembolso text,
      id_gasto_reembolso integer REFERENCES gasto(id_gasto));
    CREATE TABLE devolucion_detalle(id_devolucion integer REFERENCES devolucion(id_devolucion),
      id_producto integer,cantidad numeric(14,4),importe_reembolso numeric(14,2));
    CREATE TABLE rep(id_rep integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_cliente integer,moneda text,estado text,monto_total numeric(12,2));
    CREATE TABLE rep_factura(id_rep_factura integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_rep integer REFERENCES rep(id_rep),id_factura integer REFERENCES factura(id_factura),monto_pagado numeric(12,2));
    CREATE TABLE pago(id_pago integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      id_factura integer REFERENCES factura(id_factura),id_rep integer REFERENCES rep(id_rep),monto numeric(18,2));
    CREATE TABLE fiscal_documento(id_documento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_factura integer REFERENCES factura(id_factura),id_rep integer REFERENCES rep(id_rep),estado text NOT NULL)`);
  const audit = fs.readFileSync(path.join(__dirname, '../migrations/010_setup_audit_triggers.sql'), 'utf8');
  await client.query(audit.slice(audit.indexOf('CREATE TABLE auditoria_jsonb'), audit.indexOf('-- 3. Apply')));
  await client.query(fs.readFileSync(path.join(__dirname, '../migrations/092_vinculos_comerciales_crm.sql'), 'utf8'));
}
module.exports = { setupCommercialSchema };
