-- Ficha Cliente 360: contactos y asociación de documentos a una unidad.

CREATE TABLE IF NOT EXISTS cliente_contacto (
  id_contacto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente integer NOT NULL REFERENCES cliente("IdCliente") ON DELETE CASCADE,
  nombre varchar(150) NOT NULL,
  cargo varchar(100) NULL,
  telefono varchar(30) NULL,
  email varchar(150) NULL,
  canal_preferido varchar(20) NOT NULL DEFAULT 'Telefono'
    CHECK (canal_preferido IN ('Telefono','WhatsApp','Email','Otro')),
  es_principal boolean NOT NULL DEFAULT false,
  notas varchar(500) NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (length(btrim(nombre)) > 0),
  CHECK (telefono IS NOT NULL OR email IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_cliente_contacto_principal
  ON cliente_contacto(id_cliente) WHERE es_principal;
CREATE INDEX IF NOT EXISTS idx_cliente_contacto_cliente
  ON cliente_contacto(id_cliente, es_principal DESC, nombre);

ALTER TABLE crm_unidad_cliente ADD COLUMN IF NOT EXISTS transmision varchar(120);
ALTER TABLE crm_unidad_cliente ADD COLUMN IF NOT EXISTS diferencial varchar(120);
ALTER TABLE crm_unidad_cliente ADD COLUMN IF NOT EXISTS placas varchar(20);
ALTER TABLE cotizacion ADD COLUMN IF NOT EXISTS id_unidad integer NULL
  REFERENCES crm_unidad_cliente(id_unidad) ON DELETE SET NULL;
ALTER TABLE factura ADD COLUMN IF NOT EXISTS id_unidad integer NULL
  REFERENCES crm_unidad_cliente(id_unidad) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_cotizacion_unidad ON cotizacion(id_unidad) WHERE id_unidad IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_factura_unidad ON factura(id_unidad) WHERE id_unidad IS NOT NULL;

