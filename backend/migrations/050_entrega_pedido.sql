CREATE TABLE IF NOT EXISTS entrega_pedido (
  id_entrega bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido integer NOT NULL REFERENCES pedido_venta(id_pedido) ON DELETE CASCADE,
  recibido_por varchar(200) NULL,
  notas varchar(1000) NULL,
  id_user integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id_pedido)
);

DROP TRIGGER IF EXISTS trg_audit_jsonb_entrega_pedido ON entrega_pedido;
CREATE TRIGGER trg_audit_jsonb_entrega_pedido AFTER INSERT OR UPDATE OR DELETE ON entrega_pedido
FOR EACH ROW EXECUTE FUNCTION fn_audit_trigger();
