-- Pedidos de venta, reservas de inventario, surtido y backorders.

CREATE SEQUENCE IF NOT EXISTS pedido_venta_folio_seq START 1;

CREATE TABLE IF NOT EXISTS pedido_venta (
  id_pedido integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio bigint NOT NULL DEFAULT nextval('pedido_venta_folio_seq'),
  request_id uuid NOT NULL UNIQUE,
  id_cliente integer NOT NULL REFERENCES cliente("IdCliente"),
  id_unidad integer NULL REFERENCES crm_unidad_cliente(id_unidad) ON DELETE SET NULL,
  id_cotizacion integer NULL REFERENCES cotizacion(id_cotizacion) ON DELETE SET NULL,
  estado varchar(30) NOT NULL DEFAULT 'Borrador' CHECK (estado IN
    ('Borrador','Confirmado','En espera','Parcialmente surtido','Surtido','Entregado','Facturado','Cancelado')),
  notas varchar(2000) NULL,
  subtotal numeric(18,2) NOT NULL CHECK (subtotal >= 0),
  impuestos numeric(18,2) NOT NULL CHECK (impuestos >= 0),
  total numeric(18,2) NOT NULL CHECK (total >= 0),
  id_vendedor integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  version integer NOT NULL DEFAULT 1,
  UNIQUE (folio)
);

CREATE TABLE IF NOT EXISTS pedido_venta_detalle (
  id_detalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido integer NOT NULL REFERENCES pedido_venta(id_pedido) ON DELETE CASCADE,
  id_producto integer NOT NULL REFERENCES producto("IdProducto"),
  descripcion varchar(500) NOT NULL,
  cantidad numeric(18,6) NOT NULL CHECK (cantidad > 0),
  valor_unitario numeric(18,6) NOT NULL CHECK (valor_unitario >= 0),
  tasa_iva numeric(9,6) NOT NULL DEFAULT 0 CHECK (tasa_iva BETWEEN 0 AND 1),
  importe numeric(18,2) NOT NULL CHECK (importe >= 0),
  importe_iva numeric(18,2) NOT NULL CHECK (importe_iva >= 0),
  cantidad_reservada numeric(18,6) NOT NULL DEFAULT 0 CHECK (cantidad_reservada >= 0 AND cantidad_reservada <= cantidad),
  cantidad_surtida numeric(18,6) NOT NULL DEFAULT 0 CHECK (cantidad_surtida >= 0 AND cantidad_surtida <= cantidad_reservada),
  UNIQUE (id_pedido, id_producto)
);

CREATE TABLE IF NOT EXISTS reserva_inventario (
  id_reserva integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido integer NOT NULL REFERENCES pedido_venta(id_pedido) ON DELETE CASCADE,
  id_detalle integer NOT NULL REFERENCES pedido_venta_detalle(id_detalle) ON DELETE CASCADE,
  id_producto integer NOT NULL REFERENCES producto("IdProducto"),
  cantidad numeric(18,6) NOT NULL CHECK (cantidad > 0),
  cantidad_liberada numeric(18,6) NOT NULL DEFAULT 0 CHECK (cantidad_liberada >= 0 AND cantidad_liberada <= cantidad),
  estado varchar(20) NOT NULL DEFAULT 'Activa' CHECK (estado IN ('Activa','Surtida','Consumida','Liberada')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS backorder_cliente (
  id_backorder integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido integer NOT NULL REFERENCES pedido_venta(id_pedido) ON DELETE CASCADE,
  id_detalle integer NOT NULL REFERENCES pedido_venta_detalle(id_detalle) ON DELETE CASCADE,
  id_cliente integer NOT NULL REFERENCES cliente("IdCliente"),
  id_producto integer NOT NULL REFERENCES producto("IdProducto"),
  cantidad numeric(18,6) NOT NULL CHECK (cantidad > 0),
  cantidad_asignada numeric(18,6) NOT NULL DEFAULT 0 CHECK (cantidad_asignada >= 0 AND cantidad_asignada <= cantidad),
  prioridad smallint NOT NULL DEFAULT 3 CHECK (prioridad BETWEEN 1 AND 5),
  estado varchar(20) NOT NULL DEFAULT 'Pendiente' CHECK (estado IN ('Pendiente','Parcial','Cubierto','Cancelado')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id_detalle)
);

CREATE TABLE IF NOT EXISTS pedido_estado_historial (
  id_historial bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido integer NOT NULL REFERENCES pedido_venta(id_pedido) ON DELETE CASCADE,
  estado_anterior varchar(30) NULL,
  estado_nuevo varchar(30) NOT NULL,
  detalle varchar(1000) NULL,
  id_user integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_pedido_estado_fecha ON pedido_venta(estado, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_pedido_cliente_fecha ON pedido_venta(id_cliente, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_reserva_producto_activa ON reserva_inventario(id_producto)
  WHERE estado IN ('Activa','Surtida');
CREATE INDEX IF NOT EXISTS idx_backorder_pendiente ON backorder_cliente(prioridad, created_at)
  WHERE estado IN ('Pendiente','Parcial');

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['pedido_venta','pedido_venta_detalle','reserva_inventario','backorder_cliente'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_audit_jsonb_%I ON %I', t, t);
    EXECUTE format('CREATE TRIGGER trg_audit_jsonb_%I AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION fn_audit_trigger()', t, t);
  END LOOP;
END $$;

COMMENT ON TABLE reserva_inventario IS 'Apartados que reducen existencia disponible sin modificar la existencia física.';
COMMENT ON TABLE backorder_cliente IS 'Demanda confirmada de pedidos que no pudo reservarse por falta de existencia.';
