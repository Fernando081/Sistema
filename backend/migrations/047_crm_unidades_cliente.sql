-- Unidades y motores asociados a clientes/prospectos del CRM.
-- Permite conservar VIN del camion y ESN del motor aun antes de crear el cliente fiscal.

CREATE TABLE IF NOT EXISTS crm_unidad_cliente (
  id_unidad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente integer NULL REFERENCES cliente("IdCliente") ON DELETE CASCADE,
  id_oportunidad integer NULL REFERENCES crm_oportunidad(id_oportunidad) ON DELETE CASCADE,
  vin varchar(17) NULL,
  esn varchar(50) NULL,
  numero_economico varchar(50) NULL,
  marca varchar(80) NULL,
  modelo varchar(100) NULL,
  anio smallint NULL CHECK (anio BETWEEN 1900 AND 2200),
  motor varchar(120) NULL,
  notas varchar(1000) NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT crm_unidad_propietario CHECK (id_cliente IS NOT NULL OR id_oportunidad IS NOT NULL),
  CONSTRAINT crm_unidad_identificador CHECK (vin IS NOT NULL OR esn IS NOT NULL),
  CONSTRAINT crm_unidad_vin_valido CHECK (vin IS NULL OR vin ~ '^[A-HJ-NPR-Z0-9]{17}$'),
  CONSTRAINT crm_unidad_esn_no_vacio CHECK (esn IS NULL OR length(btrim(esn)) >= 3)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_crm_unidad_vin
  ON crm_unidad_cliente (vin) WHERE vin IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_crm_unidad_esn
  ON crm_unidad_cliente (esn) WHERE esn IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_crm_unidad_cliente
  ON crm_unidad_cliente (id_cliente, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_crm_unidad_oportunidad
  ON crm_unidad_cliente (id_oportunidad, updated_at DESC);
