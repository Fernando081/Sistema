CREATE TABLE IF NOT EXISTS app_notification (
  id_notification bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_user integer NOT NULL REFERENCES auth_user(id_user) ON DELETE CASCADE,
  type varchar(40) NOT NULL,
  title varchar(160) NOT NULL,
  message varchar(500) NOT NULL,
  severity varchar(12) NOT NULL DEFAULT 'info' CHECK(severity IN ('info','warning','critical')),
  route varchar(240),
  source_type varchar(50),
  source_id bigint,
  dedupe_key varchar(180) NOT NULL UNIQUE,
  read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS idx_notification_user_unread ON app_notification(id_user,created_at DESC) WHERE read_at IS NULL;

DROP TRIGGER IF EXISTS trg_audit_jsonb_app_notification ON app_notification;
CREATE TRIGGER trg_audit_jsonb_app_notification AFTER INSERT OR UPDATE OR DELETE ON app_notification
FOR EACH ROW EXECUTE FUNCTION fn_audit_trigger();
