-- Tareas asignables y bitácora de comunicaciones del CRM.
CREATE TABLE IF NOT EXISTS crm_tarea (
  id_tarea bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo varchar(180) NOT NULL,
  descripcion varchar(2000),
  prioridad varchar(12) NOT NULL DEFAULT 'Media' CHECK (prioridad IN ('Baja','Media','Alta','Urgente')),
  estado varchar(20) NOT NULL DEFAULT 'Pendiente' CHECK (estado IN ('Pendiente','En progreso','Completada','Cancelada')),
  fecha_vencimiento timestamptz NOT NULL,
  id_responsable integer NOT NULL REFERENCES auth_user(id_user) ON DELETE RESTRICT,
  id_cliente integer REFERENCES cliente("IdCliente") ON DELETE CASCADE,
  id_unidad integer REFERENCES crm_unidad_cliente(id_unidad) ON DELETE SET NULL,
  id_oportunidad integer REFERENCES crm_oportunidad(id_oportunidad) ON DELETE CASCADE,
  id_cotizacion integer REFERENCES cotizacion(id_cotizacion) ON DELETE SET NULL,
  id_pedido integer REFERENCES pedido_venta(id_pedido) ON DELETE SET NULL,
  id_creador integer REFERENCES auth_user(id_user) ON DELETE SET NULL,
  completada_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  version integer NOT NULL DEFAULT 1,
  CHECK (id_cliente IS NOT NULL OR id_unidad IS NOT NULL OR id_oportunidad IS NOT NULL OR id_cotizacion IS NOT NULL OR id_pedido IS NOT NULL),
  CHECK ((estado = 'Completada' AND completada_at IS NOT NULL) OR (estado <> 'Completada' AND completada_at IS NULL))
);

CREATE TABLE IF NOT EXISTS crm_comunicacion (
  id_comunicacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  canal varchar(20) NOT NULL CHECK (canal IN ('Llamada','Correo','WhatsApp','Visita','Otro')),
  direccion varchar(12) NOT NULL CHECK (direccion IN ('Entrante','Saliente')),
  resumen varchar(2000) NOT NULL,
  fecha timestamptz NOT NULL DEFAULT clock_timestamp(),
  id_cliente integer REFERENCES cliente("IdCliente") ON DELETE CASCADE,
  id_unidad integer REFERENCES crm_unidad_cliente(id_unidad) ON DELETE SET NULL,
  id_oportunidad integer REFERENCES crm_oportunidad(id_oportunidad) ON DELETE CASCADE,
  id_user integer REFERENCES auth_user(id_user) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CHECK (id_cliente IS NOT NULL OR id_unidad IS NOT NULL OR id_oportunidad IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_crm_tarea_responsable_estado ON crm_tarea(id_responsable,estado,fecha_vencimiento);
CREATE INDEX IF NOT EXISTS idx_crm_tarea_vencida ON crm_tarea(fecha_vencimiento) WHERE estado IN ('Pendiente','En progreso');
CREATE INDEX IF NOT EXISTS idx_crm_comunicacion_cliente ON crm_comunicacion(id_cliente,fecha DESC);
CREATE INDEX IF NOT EXISTS idx_crm_comunicacion_oportunidad ON crm_comunicacion(id_oportunidad,fecha DESC);

