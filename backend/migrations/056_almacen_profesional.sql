-- Almacenes, ubicaciones, transferencias, conteos, lotes, series, kits y cascos.

CREATE TABLE IF NOT EXISTS almacen (
  id_almacen integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, codigo varchar(20) NOT NULL UNIQUE,
  nombre varchar(100) NOT NULL, direccion varchar(300) NULL, activo boolean NOT NULL DEFAULT true,
  es_principal boolean NOT NULL DEFAULT false, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_almacen_principal ON almacen(es_principal) WHERE es_principal;
CREATE TABLE IF NOT EXISTS almacen_ubicacion (
  id_ubicacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_almacen integer NOT NULL REFERENCES almacen(id_almacen) ON DELETE CASCADE,
  codigo varchar(50) NOT NULL, zona varchar(50) NULL, pasillo varchar(30) NULL, anaquel varchar(30) NULL,
  nivel varchar(30) NULL, contenedor varchar(50) NULL, activa boolean NOT NULL DEFAULT true,
  UNIQUE(id_almacen,codigo)
);
CREATE TABLE IF NOT EXISTS inventario_ubicacion (
  id_ubicacion integer NOT NULL REFERENCES almacen_ubicacion(id_ubicacion) ON DELETE CASCADE,
  id_producto integer NOT NULL REFERENCES producto("IdProducto") ON DELETE CASCADE,
  cantidad numeric(18,6) NOT NULL DEFAULT 0 CHECK(cantidad>=0), updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(id_ubicacion,id_producto)
);
CREATE TABLE IF NOT EXISTS transferencia_almacen (
  id_transferencia bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id uuid NOT NULL UNIQUE,
  id_producto integer NOT NULL REFERENCES producto("IdProducto"), id_ubicacion_origen integer NOT NULL REFERENCES almacen_ubicacion(id_ubicacion),
  id_ubicacion_destino integer NOT NULL REFERENCES almacen_ubicacion(id_ubicacion), cantidad numeric(18,6) NOT NULL CHECK(cantidad>0),
  motivo varchar(500) NOT NULL, id_user integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(), CHECK(id_ubicacion_origen<>id_ubicacion_destino)
);
CREATE TABLE IF NOT EXISTS conteo_inventario (
  id_conteo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id uuid NOT NULL UNIQUE,
  id_ubicacion integer NOT NULL REFERENCES almacen_ubicacion(id_ubicacion), estado varchar(20) NOT NULL DEFAULT 'Abierto' CHECK(estado IN('Abierto','Aplicado','Cancelado')),
  notas varchar(1000) NULL,id_user integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,created_at timestamptz NOT NULL DEFAULT now(),applied_at timestamptz NULL
);
CREATE TABLE IF NOT EXISTS conteo_inventario_detalle (
  id_detalle bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_conteo integer NOT NULL REFERENCES conteo_inventario(id_conteo) ON DELETE CASCADE,
  id_producto integer NOT NULL REFERENCES producto("IdProducto"),cantidad_sistema numeric(18,6) NOT NULL,cantidad_contada numeric(18,6) NOT NULL CHECK(cantidad_contada>=0),
  diferencia numeric(18,6) GENERATED ALWAYS AS(cantidad_contada-cantidad_sistema)STORED,UNIQUE(id_conteo,id_producto)
);
CREATE TABLE IF NOT EXISTS inventario_lote (
  id_lote bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_producto integer NOT NULL REFERENCES producto("IdProducto"),id_ubicacion integer NOT NULL REFERENCES almacen_ubicacion(id_ubicacion),
  lote varchar(80) NOT NULL,fecha_caducidad date NULL,cantidad numeric(18,6) NOT NULL CHECK(cantidad>=0),created_at timestamptz NOT NULL DEFAULT now(),UNIQUE(id_producto,id_ubicacion,lote)
);
CREATE TABLE IF NOT EXISTS inventario_serie (
  id_serie bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_producto integer NOT NULL REFERENCES producto("IdProducto"),id_ubicacion integer NULL REFERENCES almacen_ubicacion(id_ubicacion),
  numero_serie varchar(120) NOT NULL UNIQUE,estado varchar(20) NOT NULL DEFAULT 'Disponible' CHECK(estado IN('Disponible','Reservada','Vendida','Garantia','Baja')),notas varchar(500) NULL,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS producto_kit_detalle (
  id_kit integer NOT NULL REFERENCES producto("IdProducto") ON DELETE CASCADE,id_componente integer NOT NULL REFERENCES producto("IdProducto"),cantidad numeric(18,6) NOT NULL CHECK(cantidad>0),PRIMARY KEY(id_kit,id_componente),CHECK(id_kit<>id_componente)
);
CREATE TABLE IF NOT EXISTS casco_recuperable (
  id_casco bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_producto integer NOT NULL REFERENCES producto("IdProducto"),id_cliente integer NULL REFERENCES cliente("IdCliente"),
  estado varchar(20) NOT NULL DEFAULT 'Pendiente' CHECK(estado IN('Pendiente','Recibido','Enviado','Acreditado','Descartado')),deposito numeric(18,2) NOT NULL DEFAULT 0 CHECK(deposito>=0),referencia varchar(100) NULL,created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now()
);

