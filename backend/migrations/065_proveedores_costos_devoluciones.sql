CREATE TABLE IF NOT EXISTS recepcion_costo_adicional (
  id_costo bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id uuid NOT NULL UNIQUE,
  id_recepcion integer NOT NULL REFERENCES recepcion_compra(id_recepcion),
  tipo varchar(30) NOT NULL CHECK(tipo IN ('Flete','Seguro','Importacion','Maniobras','Otro')),
  monto numeric(18,2) NOT NULL CHECK(monto>0),
  criterio varchar(15) NOT NULL DEFAULT 'Valor' CHECK(criterio IN ('Valor','Cantidad')),
  notas varchar(500),id_user integer REFERENCES auth_user(id_user) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS recepcion_costo_adicional_detalle (
  id_costo bigint NOT NULL REFERENCES recepcion_costo_adicional(id_costo) ON DELETE CASCADE,
  id_recepcion_detalle integer NOT NULL REFERENCES recepcion_compra_detalle(id_detalle),
  monto numeric(18,2) NOT NULL CHECK(monto>=0),PRIMARY KEY(id_costo,id_recepcion_detalle)
);
CREATE TABLE IF NOT EXISTS devolucion_proveedor (
  id_devolucion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,request_id uuid NOT NULL UNIQUE,
  id_recepcion integer NOT NULL REFERENCES recepcion_compra(id_recepcion),id_proveedor integer NOT NULL REFERENCES proveedor("IdProveedor"),
  motivo varchar(500) NOT NULL,estado varchar(20) NOT NULL DEFAULT 'Enviada' CHECK(estado IN ('Borrador','Enviada','Acreditada','Cancelada')),
  id_user integer REFERENCES auth_user(id_user) ON DELETE SET NULL,created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE IF NOT EXISTS devolucion_proveedor_detalle (
  id_detalle bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_devolucion bigint NOT NULL REFERENCES devolucion_proveedor(id_devolucion) ON DELETE CASCADE,
  id_recepcion_detalle integer NOT NULL REFERENCES recepcion_compra_detalle(id_detalle),id_producto integer NOT NULL REFERENCES producto("IdProducto"),
  cantidad numeric(18,6) NOT NULL CHECK(cantidad>0),costo_unitario numeric(18,6) NOT NULL CHECK(costo_unitario>=0),
  UNIQUE(id_devolucion,id_recepcion_detalle)
);
CREATE TABLE IF NOT EXISTS evaluacion_proveedor (
  id_evaluacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_proveedor integer NOT NULL REFERENCES proveedor("IdProveedor") ON DELETE CASCADE,
  id_orden integer REFERENCES orden_compra(id_orden) ON DELETE SET NULL,precio smallint NOT NULL CHECK(precio BETWEEN 1 AND 5),
  entrega smallint NOT NULL CHECK(entrega BETWEEN 1 AND 5),calidad smallint NOT NULL CHECK(calidad BETWEEN 1 AND 5),
  atencion smallint NOT NULL CHECK(atencion BETWEEN 1 AND 5),comentario varchar(1000),id_user integer REFERENCES auth_user(id_user) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),UNIQUE(id_orden)
);
CREATE INDEX IF NOT EXISTS idx_evaluacion_proveedor_fecha ON evaluacion_proveedor(id_proveedor,created_at DESC);
