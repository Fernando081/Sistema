-- D02: instalación reportada, revisión manual y vínculo a garantías existentes.
-- No infiere instalaciones a partir de facturas ni modifica existencias.
CREATE TABLE crm_unidad_pieza (
 id_pieza integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_unidad integer NOT NULL REFERENCES crm_unidad_cliente(id_unidad) ON DELETE RESTRICT,
 id_concepto integer NOT NULL REFERENCES conceptofactura(id_concepto) ON DELETE RESTRICT,
 request_id uuid NOT NULL, huella char(64) NOT NULL,
 cantidad numeric(18,6) NOT NULL CHECK(cantidad>0), fecha timestamptz NOT NULL,
 detalle varchar(1000) NOT NULL CHECK(length(btrim(detalle))>0),
 codigo text NOT NULL, descripcion text NOT NULL, vin text NULL, esn text NULL,
 compatibilidad varchar(20) NOT NULL CHECK(compatibilidad IN ('Pendiente','Verificada','Incompatible')),
 referencia varchar(1000) NOT NULL CHECK(length(btrim(referencia))>0),
 version integer NOT NULL DEFAULT 1 CHECK(version>0),
 id_autor integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
 autor_nombre text NOT NULL, creada_en timestamptz NOT NULL DEFAULT now(),
 revision_nombre text NOT NULL, revision_en timestamptz NOT NULL DEFAULT now(),
 anulada boolean NOT NULL DEFAULT false, motivo_anulacion varchar(1000) NULL,
 UNIQUE(id_unidad,request_id),
 CHECK((anulada AND motivo_anulacion IS NOT NULL AND length(btrim(motivo_anulacion))>0)
  OR (NOT anulada AND motivo_anulacion IS NULL))
);
CREATE INDEX crm_unidad_pieza_historial ON crm_unidad_pieza(id_unidad,fecha DESC,id_pieza DESC);
CREATE INDEX crm_unidad_pieza_origen ON crm_unidad_pieza(id_concepto) WHERE NOT anulada;

CREATE TABLE crm_unidad_pieza_garantia (
 id_vinculo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_pieza integer NOT NULL REFERENCES crm_unidad_pieza(id_pieza) ON DELETE RESTRICT,
 id_garantia integer NOT NULL REFERENCES garantia(id_garantia) ON DELETE RESTRICT,
 request_id uuid NOT NULL, huella char(64) NOT NULL,
 motivo varchar(1000) NOT NULL CHECK(length(btrim(motivo))>0),
 id_autor integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
 autor_nombre text NOT NULL, creada_en timestamptz NOT NULL DEFAULT now(),
 retirado boolean NOT NULL DEFAULT false, motivo_retiro varchar(1000) NULL,
 UNIQUE(id_pieza,request_id),
 CHECK((retirado AND motivo_retiro IS NOT NULL AND length(btrim(motivo_retiro))>0)
  OR (NOT retirado AND motivo_retiro IS NULL))
);
CREATE UNIQUE INDEX crm_pieza_garantia_activa ON crm_unidad_pieza_garantia(id_garantia) WHERE NOT retirado;
CREATE INDEX crm_pieza_garantia_historial ON crm_unidad_pieza_garantia(id_pieza,id_vinculo DESC);

CREATE TRIGGER trg_audit_jsonb_crm_unidad_pieza AFTER INSERT OR UPDATE OR DELETE ON crm_unidad_pieza
 FOR EACH ROW EXECUTE FUNCTION fn_audit_trigger();
CREATE TRIGGER trg_audit_jsonb_crm_unidad_pieza_garantia AFTER INSERT OR UPDATE OR DELETE ON crm_unidad_pieza_garantia
 FOR EACH ROW EXECUTE FUNCTION fn_audit_trigger();
