-- Conteos ciegos autorizables, movimientos de kits y trazabilidad de cascos.

ALTER TABLE conteo_inventario DROP CONSTRAINT IF EXISTS conteo_inventario_estado_check;
ALTER TABLE conteo_inventario ADD CONSTRAINT conteo_inventario_estado_check
  CHECK(estado IN('Abierto','Pendiente','Aplicado','Rechazado','Cancelado'));
ALTER TABLE conteo_inventario ADD COLUMN IF NOT EXISTS tipo varchar(20) NOT NULL DEFAULT 'Ciclico'
  CHECK(tipo IN('Ciclico','General'));
ALTER TABLE conteo_inventario ADD COLUMN IF NOT EXISTS ciego boolean NOT NULL DEFAULT true;
ALTER TABLE conteo_inventario ADD COLUMN IF NOT EXISTS id_autorizador integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL;
ALTER TABLE conteo_inventario ADD COLUMN IF NOT EXISTS authorized_at timestamptz NULL;
ALTER TABLE conteo_inventario ADD COLUMN IF NOT EXISTS motivo_rechazo varchar(500) NULL;

CREATE TABLE IF NOT EXISTS producto_kit_movimiento (
  id_movimiento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id uuid NOT NULL UNIQUE,
  id_kit integer NOT NULL REFERENCES producto("IdProducto"),
  tipo varchar(20) NOT NULL CHECK(tipo IN('Armado','Desarmado')),
  cantidad numeric(18,6) NOT NULL CHECK(cantidad>0),
  id_user integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

ALTER TABLE casco_recuperable ADD COLUMN IF NOT EXISTS id_user integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL;
ALTER TABLE casco_recuperable ADD COLUMN IF NOT EXISTS notas varchar(500) NULL;

CREATE INDEX IF NOT EXISTS idx_conteo_estado_fecha ON conteo_inventario(estado,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_casco_estado_fecha ON casco_recuperable(estado,created_at DESC);

DROP TRIGGER IF EXISTS trg_audit_jsonb_producto_kit_movimiento ON producto_kit_movimiento;
CREATE TRIGGER trg_audit_jsonb_producto_kit_movimiento
AFTER INSERT OR UPDATE OR DELETE ON producto_kit_movimiento
FOR EACH ROW EXECUTE FUNCTION fn_audit_trigger();
