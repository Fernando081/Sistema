-- Prospectos, oportunidades y seguimientos sin exigir datos fiscales.

CREATE TABLE IF NOT EXISTS crm_oportunidad (
  id_oportunidad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente integer NULL REFERENCES cliente("IdCliente") ON DELETE SET NULL,
  empresa varchar(180) NOT NULL,
  contacto varchar(150) NULL,
  telefono varchar(30) NULL,
  email varchar(150) NULL,
  tipo_cliente varchar(30) NOT NULL DEFAULT 'Otro'
    CHECK (tipo_cliente IN ('Flotilla', 'Taller', 'Transportista', 'Mostrador', 'Otro')),
  etapa varchar(30) NOT NULL DEFAULT 'Prospecto'
    CHECK (etapa IN ('Prospecto', 'Contactado', 'Cotizando', 'Negociacion', 'Ganada', 'Perdida')),
  monto_estimado numeric(18,2) NOT NULL DEFAULT 0 CHECK (monto_estimado >= 0),
  siguiente_accion varchar(255) NULL,
  fecha_siguiente_accion timestamptz NULL,
  motivo_perdida varchar(100) NULL,
  id_responsable integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS crm_seguimiento (
  id_seguimiento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_oportunidad integer NOT NULL REFERENCES crm_oportunidad(id_oportunidad) ON DELETE CASCADE,
  tipo varchar(30) NOT NULL CHECK (tipo IN ('Llamada', 'WhatsApp', 'Correo', 'Visita', 'Nota')),
  detalle text NOT NULL,
  id_user integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS venta_perdida (
  id_venta_perdida integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_oportunidad integer NULL REFERENCES crm_oportunidad(id_oportunidad) ON DELETE SET NULL,
  id_cliente integer NULL REFERENCES cliente("IdCliente") ON DELETE SET NULL,
  id_producto integer NULL REFERENCES producto("IdProducto") ON DELETE SET NULL,
  descripcion_buscada varchar(255) NOT NULL,
  cantidad numeric(18,6) NOT NULL DEFAULT 1 CHECK (cantidad > 0),
  motivo varchar(40) NOT NULL CHECK (motivo IN ('Sin existencia', 'Precio', 'Entrega', 'Compatibilidad', 'Otro')),
  notas text NULL,
  id_user integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_crm_oportunidad_etapa_accion
  ON crm_oportunidad (etapa, fecha_siguiente_accion);
CREATE INDEX IF NOT EXISTS idx_crm_seguimiento_oportunidad_fecha
  ON crm_seguimiento (id_oportunidad, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_venta_perdida_producto_fecha
  ON venta_perdida (id_producto, created_at DESC);
