-- D01: no infiere kilometraje, horas o mantenimiento de unidades históricas.
CREATE TABLE crm_unidad_lectura (
 id_lectura integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_unidad integer NOT NULL REFERENCES crm_unidad_cliente(id_unidad) ON DELETE RESTRICT,
 request_id uuid NOT NULL, huella char(64) NOT NULL,
 fecha timestamptz NOT NULL,
 kilometraje numeric(14,2) NULL CHECK(kilometraje>=0),
 horas numeric(14,2) NULL CHECK(horas>=0),
 notas varchar(1000) NOT NULL DEFAULT '',
 id_autor integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL, autor_nombre text NOT NULL,
 creada_en timestamptz NOT NULL DEFAULT now(),
 anulada boolean NOT NULL DEFAULT false, motivo_anulacion varchar(1000) NULL,
 UNIQUE(id_unidad,request_id), CHECK(kilometraje IS NOT NULL OR horas IS NOT NULL),
 CHECK((anulada AND motivo_anulacion IS NOT NULL AND length(btrim(motivo_anulacion))>0) OR (NOT anulada AND motivo_anulacion IS NULL))
);
CREATE INDEX crm_unidad_lectura_fecha ON crm_unidad_lectura(id_unidad,fecha DESC,id_lectura DESC);

CREATE TABLE crm_unidad_mantenimiento (
 id_mantenimiento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_unidad integer NOT NULL REFERENCES crm_unidad_cliente(id_unidad) ON DELETE RESTRICT,
 request_id uuid NOT NULL, huella char(64) NOT NULL,
 titulo varchar(150) NOT NULL CHECK(length(btrim(titulo))>0), notas varchar(1000) NOT NULL DEFAULT '',
 fecha_objetivo date NULL, kilometraje_objetivo numeric(14,2) NULL CHECK(kilometraje_objetivo>=0),
 horas_objetivo numeric(14,2) NULL CHECK(horas_objetivo>=0),
 estado varchar(15) NOT NULL DEFAULT 'Pendiente' CHECK(estado IN ('Pendiente','Realizado','Cancelado')),
 version integer NOT NULL DEFAULT 1 CHECK(version>0),
 fecha_realizada timestamptz NULL, detalle_cierre varchar(1000) NULL,
 id_autor integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL, autor_nombre text NOT NULL,
 id_cierre integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL, cierre_nombre text NULL,
 creada_en timestamptz NOT NULL DEFAULT now(),
 UNIQUE(id_unidad,request_id),
 CHECK(fecha_objetivo IS NOT NULL OR kilometraje_objetivo IS NOT NULL OR horas_objetivo IS NOT NULL),
 CHECK((estado='Pendiente' AND fecha_realizada IS NULL AND detalle_cierre IS NULL)
   OR (estado='Realizado' AND fecha_realizada IS NOT NULL AND detalle_cierre IS NOT NULL AND length(btrim(detalle_cierre))>0)
   OR (estado='Cancelado' AND fecha_realizada IS NULL AND detalle_cierre IS NOT NULL AND length(btrim(detalle_cierre))>0))
);
CREATE INDEX crm_unidad_mantenimiento_estado ON crm_unidad_mantenimiento(id_unidad,estado,creada_en DESC,id_mantenimiento DESC);

CREATE TABLE crm_unidad_archivo (
 id_archivo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_unidad integer NOT NULL REFERENCES crm_unidad_cliente(id_unidad) ON DELETE RESTRICT,
 request_id uuid NOT NULL, huella char(64) NOT NULL,
 titulo varchar(150) NOT NULL CHECK(length(btrim(titulo))>0), nombre varchar(200) NOT NULL,
 tipo varchar(15) NOT NULL CHECK(tipo IN ('Foto','Documento')),
 mime varchar(40) NOT NULL CHECK(mime IN ('image/jpeg','image/png','image/webp','application/pdf')),
 bytes integer NOT NULL CHECK(bytes BETWEEN 1 AND 5242880), sha256 char(64) NOT NULL,
 id_autor integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL, autor_nombre text NOT NULL,
 creada_en timestamptz NOT NULL DEFAULT now(),
 retirado boolean NOT NULL DEFAULT false, motivo_retiro varchar(1000) NULL,
 UNIQUE(id_unidad,request_id),
 CHECK((retirado AND motivo_retiro IS NOT NULL AND length(btrim(motivo_retiro))>0) OR (NOT retirado AND motivo_retiro IS NULL))
);
CREATE INDEX crm_unidad_archivo_unidad ON crm_unidad_archivo(id_unidad,id_archivo DESC);
-- Contenido separado: el trigger de metadata NO copia archivos a auditoria_jsonb.
CREATE TABLE crm_unidad_archivo_contenido (
 id_archivo integer PRIMARY KEY REFERENCES crm_unidad_archivo(id_archivo) ON DELETE RESTRICT,
 contenido bytea NOT NULL CHECK(octet_length(contenido) BETWEEN 1 AND 5242880)
);
