-- Política comercial: listas de precios, condiciones de crédito y autorizaciones.

ALTER TABLE producto ADD COLUMN IF NOT EXISTS costo_reposicion numeric(18,6) NULL CHECK(costo_reposicion>=0);
ALTER TABLE producto ADD COLUMN IF NOT EXISTS margen_minimo numeric(9,4) NOT NULL DEFAULT 0.15 CHECK(margen_minimo>=0 AND margen_minimo<1);

CREATE TABLE IF NOT EXISTS lista_precio (
  id_lista integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL UNIQUE, moneda varchar(3) NOT NULL DEFAULT 'MXN', activa boolean NOT NULL DEFAULT true,
  valid_from date NULL, valid_to date NULL, created_at timestamptz NOT NULL DEFAULT now(),
  CHECK(valid_to IS NULL OR valid_from IS NULL OR valid_to>=valid_from)
);
CREATE TABLE IF NOT EXISTS lista_precio_detalle (
  id_detalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_lista integer NOT NULL REFERENCES lista_precio(id_lista) ON DELETE CASCADE,
  id_producto integer NOT NULL REFERENCES producto("IdProducto") ON DELETE CASCADE,
  cantidad_minima numeric(18,6) NOT NULL DEFAULT 1 CHECK(cantidad_minima>0),
  precio numeric(18,6) NOT NULL CHECK(precio>=0), UNIQUE(id_lista,id_producto,cantidad_minima)
);
CREATE TABLE IF NOT EXISTS cliente_comercial (
  id_cliente integer PRIMARY KEY REFERENCES cliente("IdCliente") ON DELETE CASCADE,
  id_lista integer NULL REFERENCES lista_precio(id_lista) ON DELETE SET NULL,
  limite_credito numeric(18,2) NOT NULL DEFAULT 0 CHECK(limite_credito>=0), dias_credito integer NOT NULL DEFAULT 0 CHECK(dias_credito BETWEEN 0 AND 365),
  bloqueado boolean NOT NULL DEFAULT false, motivo_bloqueo varchar(500) NULL, updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS precio_especial_cliente (
  id_precio integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente integer NOT NULL REFERENCES cliente("IdCliente") ON DELETE CASCADE,
  id_producto integer NOT NULL REFERENCES producto("IdProducto") ON DELETE CASCADE,
  precio numeric(18,6) NOT NULL CHECK(precio>=0), valid_from date NULL, valid_to date NULL,
  created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(id_cliente,id_producto),
  CHECK(valid_to IS NULL OR valid_from IS NULL OR valid_to>=valid_from)
);
CREATE TABLE IF NOT EXISTS solicitud_autorizacion_comercial (
  id_autorizacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo varchar(25) NOT NULL CHECK(tipo IN ('Descuento','Margen bajo','Exceso credito')),
  estado varchar(15) NOT NULL DEFAULT 'Pendiente' CHECK(estado IN ('Pendiente','Aprobada','Rechazada','Utilizada','Cancelada')),
  id_cliente integer NOT NULL REFERENCES cliente("IdCliente"), id_producto integer NULL REFERENCES producto("IdProducto"),
  valor_solicitado numeric(18,6) NOT NULL, valor_referencia numeric(18,6) NOT NULL,
  motivo varchar(1000) NOT NULL, id_solicitante integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
  id_autorizador integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL, resolucion varchar(1000) NULL,
  expires_at timestamptz NULL, created_at timestamptz NOT NULL DEFAULT now(), resolved_at timestamptz NULL
);
CREATE INDEX IF NOT EXISTS idx_lista_precio_vigente ON lista_precio(activa,valid_from,valid_to);
CREATE INDEX IF NOT EXISTS idx_autorizacion_comercial_estado ON solicitud_autorizacion_comercial(estado,created_at);

