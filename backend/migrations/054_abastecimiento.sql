-- Solicitudes, órdenes de compra y recepciones parciales.

CREATE TABLE IF NOT EXISTS solicitud_compra (
  id_solicitud integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  request_id uuid NOT NULL UNIQUE,
  estado varchar(20) NOT NULL DEFAULT 'Borrador' CHECK (estado IN ('Borrador','Autorizada','Rechazada','Ordenada','Cancelada')),
  motivo varchar(1000) NULL,
  id_solicitante integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
  id_autorizador integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
  authorized_at timestamptz NULL,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS solicitud_compra_detalle (
  id_detalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_solicitud integer NOT NULL REFERENCES solicitud_compra(id_solicitud) ON DELETE CASCADE,
  id_producto integer NOT NULL REFERENCES producto("IdProducto"),
  cantidad numeric(18,6) NOT NULL CHECK (cantidad > 0),
  costo_estimado numeric(18,6) NOT NULL DEFAULT 0 CHECK (costo_estimado >= 0),
  origen varchar(20) NOT NULL DEFAULT 'Manual' CHECK (origen IN ('Manual','Backorder','Minimo','Pronostico')),
  UNIQUE(id_solicitud,id_producto)
);

CREATE TABLE IF NOT EXISTS orden_compra (
  id_orden integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  request_id uuid NOT NULL UNIQUE,
  id_solicitud integer NULL UNIQUE REFERENCES solicitud_compra(id_solicitud) ON DELETE SET NULL,
  id_proveedor integer NOT NULL REFERENCES proveedor("IdProveedor"),
  estado varchar(25) NOT NULL DEFAULT 'Emitida' CHECK (estado IN ('Borrador','Emitida','Confirmada','Parcialmente recibida','Recibida','Cancelada')),
  moneda varchar(3) NOT NULL DEFAULT 'MXN', tipo_cambio numeric(18,6) NOT NULL DEFAULT 1 CHECK(tipo_cambio>0),
  fecha_promesa date NULL, notas varchar(1000) NULL,
  subtotal numeric(18,2) NOT NULL, impuestos numeric(18,2) NOT NULL DEFAULT 0, total numeric(18,2) NOT NULL,
  id_user integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS orden_compra_detalle (
  id_detalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_orden integer NOT NULL REFERENCES orden_compra(id_orden) ON DELETE CASCADE,
  id_producto integer NOT NULL REFERENCES producto("IdProducto"),
  descripcion varchar(500) NOT NULL, cantidad numeric(18,6) NOT NULL CHECK(cantidad>0),
  cantidad_recibida numeric(18,6) NOT NULL DEFAULT 0 CHECK(cantidad_recibida>=0 AND cantidad_recibida<=cantidad),
  costo_unitario numeric(18,6) NOT NULL CHECK(costo_unitario>=0), tasa_iva numeric(9,6) NOT NULL DEFAULT 0.16,
  UNIQUE(id_orden,id_producto)
);

CREATE TABLE IF NOT EXISTS recepcion_compra (
  id_recepcion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id uuid NOT NULL UNIQUE, id_orden integer NOT NULL REFERENCES orden_compra(id_orden),
  referencia varchar(100) NULL, notas varchar(1000) NULL,
  id_user integer NULL REFERENCES auth_user(id_user) ON DELETE SET NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS recepcion_compra_detalle (
  id_detalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_recepcion integer NOT NULL REFERENCES recepcion_compra(id_recepcion) ON DELETE CASCADE,
  id_orden_detalle integer NOT NULL REFERENCES orden_compra_detalle(id_detalle),
  id_producto integer NOT NULL REFERENCES producto("IdProducto"), cantidad numeric(18,6) NOT NULL CHECK(cantidad>0),
  costo_unitario numeric(18,6) NOT NULL CHECK(costo_unitario>=0), UNIQUE(id_recepcion,id_orden_detalle)
);

CREATE INDEX IF NOT EXISTS idx_solicitud_compra_estado ON solicitud_compra(estado,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orden_compra_estado ON orden_compra(estado,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_recepcion_compra_orden ON recepcion_compra(id_orden,created_at DESC);

