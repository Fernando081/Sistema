-- Segmentos, campañas planificadas, plantillas, satisfacción y metas comerciales.
CREATE TABLE IF NOT EXISTS crm_segmento (
  id_segmento integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nombre varchar(120) NOT NULL UNIQUE,
  descripcion varchar(500),tipo_cliente varchar(30),dias_inactivo integer CHECK(dias_inactivo IS NULL OR dias_inactivo>=0),
  activo boolean NOT NULL DEFAULT true,id_user integer REFERENCES auth_user(id_user) ON DELETE SET NULL,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS crm_plantilla (
  id_plantilla integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nombre varchar(120) NOT NULL,
  canal varchar(20) NOT NULL CHECK(canal IN('Llamada','Correo','WhatsApp')),asunto varchar(180),contenido text NOT NULL,
  activa boolean NOT NULL DEFAULT true,id_user integer REFERENCES auth_user(id_user) ON DELETE SET NULL,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS crm_campana (
  id_campana integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,nombre varchar(150) NOT NULL,id_segmento integer REFERENCES crm_segmento(id_segmento),
  id_plantilla integer REFERENCES crm_plantilla(id_plantilla),estado varchar(20) NOT NULL DEFAULT 'Borrador' CHECK(estado IN('Borrador','Activa','Finalizada','Cancelada')),
  fecha_inicio date,fecha_fin date,objetivo varchar(500),id_user integer REFERENCES auth_user(id_user) ON DELETE SET NULL,created_at timestamptz NOT NULL DEFAULT now(),
  CHECK(fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin>=fecha_inicio)
);
CREATE TABLE IF NOT EXISTS crm_encuesta_satisfaccion (
  id_encuesta bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_cliente integer REFERENCES cliente("IdCliente") ON DELETE SET NULL,
  id_oportunidad integer REFERENCES crm_oportunidad(id_oportunidad) ON DELETE SET NULL,calificacion smallint NOT NULL CHECK(calificacion BETWEEN 1 AND 5),
  comentario varchar(1000),id_user integer REFERENCES auth_user(id_user) ON DELETE SET NULL,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS crm_meta_vendedor (
  id_meta integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,id_user integer NOT NULL REFERENCES auth_user(id_user) ON DELETE CASCADE,
  fecha_inicio date NOT NULL,fecha_fin date NOT NULL,monto_objetivo numeric(18,2) NOT NULL CHECK(monto_objetivo>=0),
  oportunidades_objetivo integer NOT NULL DEFAULT 0 CHECK(oportunidades_objetivo>=0),created_at timestamptz NOT NULL DEFAULT now(),
  CHECK(fecha_fin>=fecha_inicio),UNIQUE(id_user,fecha_inicio,fecha_fin)
);
CREATE INDEX IF NOT EXISTS idx_crm_campana_estado ON crm_campana(estado,fecha_inicio);
CREATE INDEX IF NOT EXISTS idx_crm_encuesta_cliente ON crm_encuesta_satisfaccion(id_cliente,created_at DESC);
