-- 032_catalogo_diesel_y_garantias.sql
-- Números de parte, aplicaciones y base de garantías para refacciones diésel.

CREATE TABLE IF NOT EXISTS producto_numero_parte (
  id_numero integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto integer NOT NULL REFERENCES producto("IdProducto") ON DELETE CASCADE,
  tipo varchar(20) NOT NULL CHECK (tipo IN ('OEM', 'Fabricante', 'Alterno')),
  fabricante varchar(80) NULL,
  numero varchar(80) NOT NULL,
  numero_normalizado varchar(80) GENERATED ALWAYS AS
    (lower(regexp_replace(numero, '[^[:alnum:]]', '', 'g'))) STORED,
  UNIQUE (tipo, fabricante, numero_normalizado)
);

CREATE TABLE IF NOT EXISTS producto_aplicacion (
  id_aplicacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_producto integer NOT NULL REFERENCES producto("IdProducto") ON DELETE CASCADE,
  fabricante_equipo varchar(80) NULL,
  modelo varchar(100) NULL,
  motor varchar(100) NULL,
  anio_desde smallint NULL CHECK (anio_desde BETWEEN 1900 AND 2200),
  anio_hasta smallint NULL CHECK (anio_hasta BETWEEN 1900 AND 2200),
  restricciones varchar(255) NULL,
  CHECK (anio_desde IS NULL OR anio_hasta IS NULL OR anio_desde <= anio_hasta)
);

CREATE TABLE IF NOT EXISTS garantia (
  id_garantia integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_factura integer NOT NULL REFERENCES factura(id_factura),
  id_concepto integer NOT NULL REFERENCES conceptofactura(id_concepto),
  id_proveedor integer NULL REFERENCES proveedor("IdProveedor") ON DELETE SET NULL,
  estado varchar(30) NOT NULL DEFAULT 'Recibida'
    CHECK (estado IN ('Recibida', 'En revision', 'Enviada proveedor', 'Aprobada', 'Rechazada', 'Cerrada')),
  motivo varchar(255) NOT NULL,
  resolucion text NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_producto_numero_normalizado
  ON producto_numero_parte (numero_normalizado);
CREATE INDEX IF NOT EXISTS idx_producto_aplicacion_busqueda
  ON producto_aplicacion (lower(COALESCE(motor, '')), lower(COALESCE(modelo, '')));
CREATE INDEX IF NOT EXISTS idx_garantia_estado_fecha ON garantia (estado, created_at DESC);
