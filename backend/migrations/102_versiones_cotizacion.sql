-- V01: snapshots explícitos; no rellena ni acepta cotizaciones históricas.
CREATE TABLE cotizacion_revision (
 id_revision integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cotizacion integer NOT NULL UNIQUE REFERENCES cotizacion(id_cotizacion) ON DELETE RESTRICT,
 id_raiz integer NOT NULL REFERENCES cotizacion(id_cotizacion) ON DELETE RESTRICT,
 numero integer NOT NULL CHECK(numero>0), request_id uuid NOT NULL,
 huella char(64) NOT NULL, snapshot jsonb NOT NULL CHECK(jsonb_typeof(snapshot)='object'), sha256 char(64) NOT NULL,
 motivo varchar(1000) NOT NULL CHECK(length(btrim(motivo))>0),
 autor_nombre text NOT NULL, creada_en timestamptz NOT NULL DEFAULT now(),
 UNIQUE(id_raiz,numero), UNIQUE(id_raiz,request_id)
);
CREATE TABLE cotizacion_invitacion (
 id_invitacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_revision integer NOT NULL REFERENCES cotizacion_revision(id_revision) ON DELETE RESTRICT,
 request_id uuid NOT NULL, token_hash char(64) NOT NULL UNIQUE,
 autor_nombre text NOT NULL, creada_en timestamptz NOT NULL DEFAULT now(), vence_en timestamptz NOT NULL,
 revocada boolean NOT NULL DEFAULT false, motivo_revocacion varchar(1000) NULL,
 UNIQUE(id_revision,request_id), CHECK(vence_en>creada_en),
 CHECK((revocada AND motivo_revocacion IS NOT NULL AND length(btrim(motivo_revocacion))>0) OR (NOT revocada AND motivo_revocacion IS NULL))
);
CREATE INDEX cotizacion_invitacion_revision ON cotizacion_invitacion(id_revision,id_invitacion DESC);
CREATE TABLE cotizacion_respuesta (
 id_respuesta integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_revision integer NOT NULL UNIQUE REFERENCES cotizacion_revision(id_revision) ON DELETE RESTRICT,
 id_invitacion integer NOT NULL REFERENCES cotizacion_invitacion(id_invitacion) ON DELETE RESTRICT,
 request_id uuid NOT NULL, huella char(64) NOT NULL,
 decision varchar(10) NOT NULL CHECK(decision IN ('Aceptada','Rechazada')),
 nombre varchar(150) NOT NULL CHECK(length(btrim(nombre))>0),
 comentario varchar(1000) NOT NULL CHECK(length(btrim(comentario))>0),
 confirmacion boolean NOT NULL CHECK(confirmacion), creada_en timestamptz NOT NULL DEFAULT now()
);
CREATE FUNCTION fn_cotizacion_evidencia_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'La evidencia de revisión/respuesta se conserva; crea una nueva revisión'; END $$;
CREATE TRIGGER cotizacion_revision_inmutable BEFORE UPDATE OR DELETE OR TRUNCATE ON cotizacion_revision
 FOR EACH STATEMENT EXECUTE FUNCTION fn_cotizacion_evidencia_inmutable();
CREATE TRIGGER cotizacion_respuesta_inmutable BEFORE UPDATE OR DELETE OR TRUNCATE ON cotizacion_respuesta
 FOR EACH STATEMENT EXECUTE FUNCTION fn_cotizacion_evidencia_inmutable();
ALTER TABLE cotizacion_revision ENABLE ALWAYS TRIGGER cotizacion_revision_inmutable;
ALTER TABLE cotizacion_respuesta ENABLE ALWAYS TRIGGER cotizacion_respuesta_inmutable;
DO $$DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['cotizacion_revision','cotizacion_invitacion','cotizacion_respuesta'] LOOP
 EXECUTE format('CREATE TRIGGER trg_audit_versiones AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION fn_audit_trigger()',t);
 END LOOP;
END $$;
