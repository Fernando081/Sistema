  fs.writeFileSync(artifact, JSON.stringify({ phase: 'WEB05.2b', source: 'isolated-test-fixtures', node: process.versions.node,
    generatedAt: new Date().toISOString(), checks, cleaned, measured,
    limits: ['Esquema mínimo, no AppModule/cron/carga masiva ni aceptación comercial o PAC real.'] }, null, 2) + '\n');
